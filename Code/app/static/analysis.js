// Data analysis views and the Data analysis -> Model bridge.
//
// The scatterplot drawing is a port of analysis/scatterplots.py's standalone report (same axes,
// log toggle, tooltips and common SoH axis). Data comes from /api/analysis/*, which serves the
// observed table without interpolation or imputation.
(() => {
  "use strict";

  const NS = "http://www.w3.org/2000/svg";
  const $ = (id) => document.getElementById(id);

  const BATTERY_COLORS = { B0005: "#38bdf8", B0006: "#f59e0b", B0007: "#10b981", B0018: "#a78bfa" };
  const FALLBACK_COLORS = ["#38bdf8", "#f59e0b", "#10b981", "#a78bfa", "#f43f5e", "#94a3b8"];
  const COLUMNS_ALL = "ALL";

  let data = null; // /api/analysis/relationships
  let statsByKey = new Map();
  let targetRange = [0, 100];
  let bridgeLoaded = false;
  let resizeTimer = null;

  // ---- helpers ------------------------------------------------------------------------
  function el(tag, attrs = {}, text) {
    const node = document.createElementNS(NS, tag);
    for (const [key, value] of Object.entries(attrs)) node.setAttribute(key, value);
    if (text !== undefined) node.textContent = text;
    return node;
  }

  function html(tag, props = {}, text) {
    const node = document.createElement(tag);
    for (const [key, value] of Object.entries(props)) {
      if (key === "className") node.className = value;
      else if (key === "style") node.style.cssText = value;
      else node.setAttribute(key, value);
    }
    if (text !== undefined) node.textContent = text;
    return node;
  }

  function signed(value) {
    return value === null || value === undefined ? "n/a" : (value >= 0 ? "+" : "") + value.toFixed(3);
  }

  function tick(value) {
    const v = Math.abs(value) < 1e-12 ? 0 : value;
    const abs = Math.abs(v);
    return v.toLocaleString("en-US", {
      maximumFractionDigits: abs < 1 ? 3 : abs < 10 ? 2 : abs < 100 ? 1 : 0,
    });
  }

  function extent(values) {
    const lo = Math.min(...values);
    const hi = Math.max(...values);
    const pad = (hi - lo || Math.abs(lo) * 0.1 || 1) * 0.055;
    return [lo - pad, hi + pad];
  }

  function batteryColor(battery) {
    return BATTERY_COLORS[battery] || FALLBACK_COLORS[data.batteries.indexOf(battery) % FALLBACK_COLORS.length];
  }

  function stat(battery, feature) {
    return statsByKey.get(`${battery}|${feature}`);
  }

  // Diverging tint for correlation cells: sky for positive, rose for negative.
  function tint(rho) {
    if (rho === null || rho === undefined) return "transparent";
    const alpha = 0.06 + 0.34 * Math.min(1, Math.abs(rho));
    return rho >= 0 ? `rgba(56, 189, 248, ${alpha.toFixed(3)})` : `rgba(244, 63, 94, ${alpha.toFixed(3)})`;
  }

  function showError(containerId, message) {
    const container = $(containerId);
    if (!container) return;
    container.replaceChildren(html("div", { className: "load-error", role: "alert" }, message));
  }

  // ---- Feature relationships ----------------------------------------------------------
  async function loadRelationships() {
    try {
      const response = await fetch("/api/analysis/relationships");
      if (!response.ok) {
        const body = await response.json().catch(() => ({}));
        throw new Error(body.detail || `${response.status} ${response.statusText}`);
      }
      data = await response.json();
    } catch (error) {
      $("relCoverage").textContent = "Unavailable";
      showError("relPlots", `The data analysis could not be loaded: ${error.message}`);
      return;
    }
    statsByKey = new Map(data.stats.map((s) => [`${s.battery_id}|${s.feature}`, s]));
    targetRange = extent(data.rows.map((row) => row[2]));
    buildControls();
    buildPlotCards();
    draw();
  }

  function buildControls() {
    const select = $("relBattery");
    select.replaceChildren();
    for (const battery of [COLUMNS_ALL, ...data.batteries]) {
      select.append(html("option", { value: battery }, battery === COLUMNS_ALL ? "All batteries" : battery));
    }
    select.addEventListener("change", draw);
    $("relLog").addEventListener("change", drawPanels);

    const quality = `${data.flagged.count} cycles have four flagged charge measurements omitted. Each panel uses its available feature–target pairs (n); the other feature measurements and all targets are kept. Nothing on this tab is interpolated, imputed or fitted.`;
    $("relQuality").textContent = quality;
    $("relSource").textContent = `Source: ${data.source.table}, generated by analysis/run_eda.py from the pinned battery data (commit ${data.source.pinned.commit.slice(0, 7)}${data.source.pinned.verified ? ", checksums verified" : ", CHECKSUM MISMATCH"}). Capacity is excluded from the features because it directly defines SoH. Values above 100% are preserved.`;
  }

  function buildPlotCards() {
    const grid = $("relPlots");
    grid.replaceChildren();
    data.features.forEach((feature, index) => {
      const card = html("section", { className: "plot-card" });
      card.append(html("h3", {}, feature.title));
      card.append(html("div", { className: "plot-stat", id: `relStat-${index}` }));
      const svg = el("svg", { id: `relPlot-${index}`, role: "img", "aria-label": `${feature.title} versus state of health` });
      card.append(svg);
      grid.append(card);
    });
  }

  function draw() {
    if (!data) return;
    const battery = $("relBattery").value;
    const rows = data.rows.filter((row) => battery === COLUMNS_ALL || row[0] === battery);
    $("relCoverage").textContent = `${rows.length} cycles · ${data.features.length} features · common SoH axis`;

    const legend = $("relLegend");
    legend.replaceChildren();
    for (const b of data.batteries) {
      if (battery !== COLUMNS_ALL && battery !== b) continue;
      const swatch = html("i", { className: "swatch", style: `background:${batteryColor(b)}` });
      const item = html("span");
      item.append(swatch, document.createTextNode(b));
      legend.append(item);
    }
    renderRhoTable(battery);
    drawPanels();
  }

  function renderRhoTable(selected) {
    const table = $("rhoTable");
    table.replaceChildren();
    const columns = [COLUMNS_ALL, ...data.batteries];

    const headRow = table.createTHead().insertRow();
    headRow.append(html("th", { scope: "col" }, "Feature"));
    for (const column of columns) {
      const th = html("th", { scope: "col", className: column === selected ? "col-selected" : "" },
        column === COLUMNS_ALL ? "All batteries" : column);
      headRow.append(th);
    }

    const body = table.createTBody();
    data.features.forEach((feature) => {
      const row = body.insertRow();
      const first = row.insertCell();
      first.className = "feat";
      first.append(document.createTextNode(feature.key), html("small", {}, feature.title));
      for (const column of columns) {
        const s = stat(column, feature.key);
        const cell = row.insertCell();
        cell.className = "rho" + (column === selected ? " col-selected" : "");
        cell.textContent = signed(s.spearman_rho);
        cell.style.background = tint(s.spearman_rho);
        cell.title = `${column === COLUMNS_ALL ? "All batteries" : column}: n=${s.n_pairs}`
          + (s.omitted_pairs ? ` (${s.omitted_pairs} flagged omitted)` : "")
          + ` · Pearson r ${signed(s.pearson_r)} · Spearman ρ ${signed(s.spearman_rho)}`;
      }
    });
  }

  function drawPanels() {
    if (!data) return;
    const battery = $("relBattery").value;
    const rows = data.rows.filter((row) => battery === COLUMNS_ALL || row[0] === battery);
    const logRest = $("relLog").checked;

    data.features.forEach((feature, i) => {
      const svg = $(`relPlot-${i}`);
      svg.replaceChildren();
      const column = i + 3; // rows are [battery, cycle, soh, ...features]
      const pairs = rows.filter((row) => Number.isFinite(row[column]) && Number.isFinite(row[2]));
      const s = stat(battery, feature.key);
      $(`relStat-${i}`).textContent =
        `${feature.key} · n=${pairs.length} · r ${signed(s.pearson_r)} · ρ ${signed(s.spearman_rho)}`;

      const width = Math.max(svg.clientWidth, 240);
      const height = 205, left = 45, right = 12, top = 12, bottom = 46;
      const plotWidth = width - left - right, plotHeight = height - top - bottom;
      svg.setAttribute("viewBox", `0 0 ${width} ${height}`);

      if (!pairs.length) {
        svg.append(el("text", { x: width / 2, y: height / 2, "text-anchor": "middle" }, "No observed pairs"));
        return;
      }

      const log = feature.key === "rest_time_hours" && logRest;
      const transform = (x) => (log ? Math.log1p(x) : x);
      const inverse = (x) => (log ? Math.expm1(x) : x);
      let [xmin, xmax] = extent(pairs.map((row) => transform(row[column])));
      if (feature.key === "rest_time_hours") xmin = Math.max(0, xmin);
      const [ymin, ymax] = targetRange;
      const sx = (x) => left + ((transform(x) - xmin) / (xmax - xmin)) * plotWidth;
      const sy = (y) => top + ((ymax - y) / (ymax - ymin)) * plotHeight;

      svg.append(el("desc", {}, `${pairs.length} observed pairs for ${battery}. Pearson r ${signed(s.pearson_r)}; Spearman rho ${signed(s.spearman_rho)}.`));
      for (let j = 0; j <= 3; j++) {
        const y = ymin + ((ymax - ymin) * j) / 3;
        const tx = xmin + ((xmax - xmin) * j) / 3;
        const x = left + (plotWidth * j) / 3;
        svg.append(el("line", { x1: left, y1: sy(y), x2: width - right, y2: sy(y), stroke: "var(--border-subtle)", "stroke-width": 0.7 }));
        svg.append(el("text", { x: left - 6, y: sy(y) + 4, "text-anchor": "end" }, tick(y)));
        svg.append(el("text", { x, y: height - bottom + 17, "text-anchor": "middle" }, tick(inverse(tx))));
      }
      svg.append(el("line", { x1: left, y1: top, x2: left, y2: height - bottom, stroke: "var(--border-strong)" }));
      svg.append(el("line", { x1: left, y1: height - bottom, x2: width - right, y2: height - bottom, stroke: "var(--border-strong)" }));

      for (const row of pairs) {
        const point = el("circle", { cx: sx(row[column]), cy: sy(row[2]), r: 2.5, fill: batteryColor(row[0]), opacity: 0.6 });
        point.append(el("title", {}, `${row[0]} · cycle ${row[1]}\n${feature.key}: ${row[column].toPrecision(6)}\nSoH: ${row[2].toFixed(2)}%`));
        svg.append(point);
      }
      svg.append(el("text", { x: left + plotWidth / 2, y: height - 7, "text-anchor": "middle" }, feature.axis + (log ? " · log(1+x)" : "")));
      const cy = top + plotHeight / 2;
      svg.append(el("text", { x: 12, y: cy, "text-anchor": "middle", transform: `rotate(-90 12 ${cy})` }, "SoH (%)"));
    });
  }

  // ---- Embedded reports ---------------------------------------------------------------
  // The reports colour themselves with light-dark(), and the embedding page's colour scheme does
  // not reach them. They are served from this origin, so follow the app's dark theme directly.
  function followAppTheme(frame) {
    try {
      frame.contentDocument.documentElement.style.colorScheme = "dark";
    } catch (error) {
      /* a cross-origin frame keeps its own scheme */
    }
  }

  function loadFrame(frameId) {
    const frame = $(frameId);
    if (!frame || frame.getAttribute("src")) return;
    frame.addEventListener("load", () => followAppTheme(frame));
    frame.setAttribute("src", frame.dataset.src);
  }

  // ---- Data analysis -> Model bridge -----------------------------------------------------
  const TIMING_LABELS = {
    known: ["✓ known", "timing-known"],
    later: ["✗ later", "timing-later"],
    unconfirmed: ["? unconfirmed", "timing-unconfirmed"],
  };
  const DIRECTION_LABELS = {
    agrees: ["same sign", "dir-agrees"],
    opposite: ["opposite sign", "dir-opposite"],
    unclear: ["ρ ≈ 0", "dir-unclear"],
  };

  function timingCell(entry) {
    const cell = html("td");
    if (!entry) {
      cell.textContent = "n/a";
      return cell;
    }
    const [label, cls] = TIMING_LABELS[entry.status] || ["?", ""];
    cell.className = cls;
    cell.textContent = label;
    cell.title = `${entry.available} observed · ${entry.later} later · ${entry.unknown} unknown completion · ${entry.flagged} flagged (of ${entry.total})`;
    return cell;
  }

  async function loadBridge() {
    if (bridgeLoaded) return;
    try {
      const response = await fetch("/api/analysis/bridge");
      if (!response.ok) {
        const body = await response.json().catch(() => ({}));
        throw new Error(body.detail || `${response.status} ${response.statusText}`);
      }
      renderBridge(await response.json());
      bridgeLoaded = true;
    } catch (error) {
      $("carryoverCount").textContent = "unavailable";
      showError("carryoverList", `The notes from the data analysis could not be loaded: ${error.message}`);
    }
  }

  function renderBridge(bridge) {
    $("carryoverCount").textContent = `${bridge.caveats.length} notes`;
    const list = $("carryoverList");
    list.replaceChildren();
    for (const caveat of bridge.caveats) {
      const item = html("li");
      item.append(html("strong", {}, `${caveat.title}. `), document.createTextNode(caveat.text));
      list.append(item);
    }

    const table = $("bridgeTable");
    table.replaceChildren();
    const head = table.createTHead().insertRow();
    for (const label of ["Feature", "Spearman ρ with SoH", "Ridge weight", "Weight vs ρ", "At charge end", "At discharge start"]) {
      head.append(html("th", { scope: "col" }, label));
    }
    const body = table.createTBody();
    for (const feature of bridge.features) {
      const row = body.insertRow();
      row.insertCell().className = "feat";
      row.cells[0].textContent = feature.key;
      const rho = row.insertCell();
      rho.className = "num";
      rho.textContent = signed(feature.spearman_all);
      rho.style.background = tint(feature.spearman_all);
      const weight = row.insertCell();
      weight.className = "num";
      weight.textContent = signed(feature.ridge_weight);
      const [label, cls] = DIRECTION_LABELS[feature.direction];
      const direction = row.insertCell();
      direction.className = cls;
      direction.textContent = label;
      row.append(timingCell(feature.timing.end_of_charge), timingCell(feature.timing.discharge_start));
    }

    $("bridgeNote").textContent =
      `Ridge weights are standardized and come from the model fitted on all ${bridge.trained_on.cycles} cycles (${bridge.trained_on.table}). ρ is the pooled Spearman correlation on observed cycles from the Data analysis tab. "ρ ≈ 0" means |ρ| < ${bridge.weak_rho}. Hover a timing cell for cycle counts.`;
  }

  // ---- wiring -------------------------------------------------------------------------
  document.addEventListener("tabchange", (event) => {
    const { tab, group } = event.detail;
    if (tab === "tab-relationships") requestAnimationFrame(drawPanels);
    if (tab === "tab-clusters") loadFrame("frameClusters");
    if (tab === "tab-report") loadFrame("frameReport");
    if (group === "model") loadBridge();
  });

  document.addEventListener("click", (event) => {
    const target = event.target.closest("[data-goto]");
    if (target && window.AppNav) window.AppNav.activate(target.dataset.goto);
  });

  window.addEventListener("resize", () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(() => {
      if ($("tab-relationships")?.classList.contains("active")) drawPanels();
    }, 80);
  });

  document.addEventListener("DOMContentLoaded", loadRelationships);
})();
